#!/usr/bin/env python
"""make_scorecard.py -- build scorecard.svg and SCORECARD.md: every sealed test of this project, the failure included.

The outcomes are those of the lab ledger, exported in results/ledger-hawking.json (its "settle" rows); the script stops
if an outcome below disagrees with the export, or if the export has a settled seal that is not listed here.
Run from anywhere:  python tools/make_scorecard.py
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R = os.path.join(ROOT, 'results')

# (section, [(test, seal, what, outcome, detail, source)])
TESTS = [
    ('THE ENTROPY LEDGER (BALL ARITHMETIC)', [
        ('HK-1', '53d448f307', 'Certified Page constants, attempt 1', 'FAILED',
         'PH4, PH5 pass; PH1-PH3, PH6 INCONCLUSIVE: a quadrature remainder was not controlled (channel s = 1, l = 8), '
         'so no total was produced', 'hk1/result_hk1.json'),
        ('HK-1b', '2040a9985f', 'Certified Page constants, re-test with the same predictions', 'HOLD',
         'PH1-PH6 pass: beta, Page time, photon power, alpha, both entropy rates, graviton power inside Newton 2026',
         'hk1b/result_hk1b.json'),
    ]),
]
AMENDMENTS = [('48cf09638b', 'AMEND-HK-1-1', 'how a predicted value printed to n digits is compared with an enclosure '
               '(overlap with its rounding interval); sealed before the first main run, carried over to HK-1b',
               'seals/AMEND-HK-1-1.md')]


def export_outcomes():
    rows = json.load(open(os.path.join(R, 'ledger-hawking.json'), encoding='utf-8'))
    return {r['seal_id']: r['outcome'] for r in rows if r.get('kind') == 'settle' and 'outcome' in r}


FONT = 'Segoe UI, Helvetica, Arial, sans-serif'
INK, MUTED, ACCENT, BAND, LINE, BORDER = '#e8edf2', '#9aa4ae', '#39ff14', '#262b31', '#22272e', '#2f353d'
CHIP = {'HOLD': ('#12301c', '#39ff14'), 'FAILED': ('#3a1a1a', '#ff6b6b'), 'VOID': ('#33290f', '#ffc94d')}


def tw(s, per=7.4):
    return round(len(s) * per)


def esc(s):
    return s.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')


def build():
    exp = export_outcomes()
    counts = {'HOLD': 0, 'FAILED': 0, 'VOID': 0}
    for _, tests in TESTS:
        for tid, seal, _, outcome, _, _ in tests:
            counts[outcome] += 1
            if exp.get(seal) != outcome:
                sys.exit('ledger export disagrees for %s %s: %r' % (tid, seal, exp.get(seal)))
    if set(exp) - {s for _, ts in TESTS for _, s, *_ in ts}:
        sys.exit('ledger export has a settled seal not in the table')
    n = sum(counts.values())
    title = 'Scorecard: %d sealed tests (%d HOLD, %d FAILED)' % (n, counts['HOLD'], counts['FAILED'])
    sub = 'Sealed = prediction and pass bar hashed before the run. Failures are shown as failures. Details: SCORECARD.md.'
    W, y, body = 900, 66, []
    for head, rows in TESTS:
        body.append(f'<rect x="10" y="{y}" width="{W - 20}" height="22" fill="{BAND}"/>')
        body.append(f'<text x="20" y="{y + 16}" font-size="11.5" font-weight="600" fill="{ACCENT}" '
                    f'letter-spacing="0.5">{esc(head)}</text>')
        y += 22
        for tid, seal, what, outcome, _, _ in rows:
            body.append(f'<text x="20" y="{y + 22}" font-size="12.5" font-family="Consolas, Menlo, monospace" '
                        f'fill="{INK}">{esc(tid + " " + seal)}</text>')
            body.append(f'<text x="190" y="{y + 22}" font-size="12.5" fill="{INK}">{esc(what)}</text>')
            fill, fg = CHIP[outcome]
            t = tw(outcome)
            body.append(f'<rect x="620" y="{y + 8}" width="{t + 20}" height="20" rx="10" fill="{fill}"/>')
            body.append(f'<text x="630" y="{y + 22}" font-size="11.5" font-weight="600" fill="{fg}" '
                        f'textLength="{t}" lengthAdjust="spacingAndGlyphs">{outcome}</text>')
            y += 30
            body.append(f'<line x1="10" y1="{y + 1}" x2="{W - 10}" y2="{y + 1}" stroke="{LINE}"/>')
        y += 8
    H = y + 6
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}" font-family="{FONT}" '
           f'role="img" aria-label="{esc(title)}">\n<title>{esc(title)}</title>\n'
           f'<rect width="{W}" height="{H}" rx="10" fill="#1c2026" stroke="{BORDER}"/>\n'
           f'<text x="20" y="34" font-size="18" font-weight="600" fill="{INK}">{esc(title)}</text>\n'
           f'<text x="20" y="54" font-size="12" fill="{MUTED}">{esc(sub)}</text>\n' + '\n'.join(body) + '\n</svg>\n')
    with open(os.path.join(ROOT, 'scorecard.svg'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(svg)
    chip = {k: '![%s](brand/chips/%s.svg)' % (k, k.lower()) for k in CHIP}
    md = ['# Scorecard', '', title + '.', '',
          'Generated by `tools/make_scorecard.py`. A sealed test is one whose predictions and pass bars were hashed before',
          'its run. Both outcomes are checked against the ledger export `results/ledger-hawking.json`. The sealed bar',
          'files, the run logs and the result files of both tests are shipped.', '',
          '| Section | Test | Seal | What was predicted | Verdict | As scored | Source |',
          '|---|---|---|---|---|---|---|']
    for head, rows in TESTS:
        sec = head.split(' (')[0].capitalize()
        for tid, seal, what, outcome, detail, src in rows:
            md.append(f'| {sec} | {tid} | `{seal}` | {what} | {chip[outcome]} | {detail} | '
                      f'[results/{src}](results/{src}) |')
    md += ['', 'Amendment (sealed, not a test):', '']
    for seal, name, what, src in AMENDMENTS:
        md.append(f'- `{seal}` {name}: {what} ([results/{src}](results/{src})).')
    md += ['', 'Notes:',
           '- HK-1 is the instructive failure. Every channel it finished lay inside the predicted values, but one sub-interval',
           '  of the quadrature in channel s = 1, l = 8 could not be closed: the polynomial |P|² was evaluated as a ball on a',
           '  shifted interval, and that ball contained 0 at every halving depth. Its bar said such a run gives no claim, so',
           '  it was scored FAILED as sealed. HK-1b re-centres the polynomial exactly before the ball step, adds a rigorous',
           '  fallback for any piece that still fails (none did), and was sealed with the same predictions before its run.',
           '- PH6 is the null test: the same pipeline with the wrong (spin-1) potential must miss the graviton power. It does.',
           '- After the HOLD, two internal hostile referee rounds and a blind second implementation followed; see',
           '  `results/referee/` and `results/blind/`. Their checks are after the fact and change no sealed outcome.']
    with open(os.path.join(ROOT, 'SCORECARD.md'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(md) + '\n')
    print(title)


if __name__ == '__main__':
    build()
